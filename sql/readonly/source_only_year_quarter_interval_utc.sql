-- Canonical source-only quarter counts using fixed UTC epoch boundaries.
-- READ-ONLY; avoids session-timezone-dependent FROM_UNIXTIME/YEAR/QUARTER.
WITH source_only AS (
 SELECT s.dateTime,s.`interval` AS interval_min,s.usUnits FROM old_weewx.archive s LEFT JOIN loucka_reconstruction.archive r ON r.dateTime=s.dateTime WHERE s.dateTime>=1230768000 AND s.dateTime<1609459200 AND r.dateTime IS NULL
 UNION
 SELECT s.dateTime,s.`interval` AS interval_min,s.usUnits FROM weewx_WH1080.archive s LEFT JOIN loucka_reconstruction.archive r ON r.dateTime=s.dateTime WHERE s.dateTime>=1230768000 AND s.dateTime<1609459200 AND r.dateTime IS NULL
)
SELECT CASE WHEN dateTime < 1238544000 THEN '2009-Q1'
       WHEN dateTime < 1246406400 THEN '2009-Q2'
       WHEN dateTime < 1254355200 THEN '2009-Q3'
       WHEN dateTime < 1262304000 THEN '2009-Q4'
       WHEN dateTime < 1270080000 THEN '2010-Q1'
       WHEN dateTime < 1277942400 THEN '2010-Q2'
       WHEN dateTime < 1285891200 THEN '2010-Q3'
       WHEN dateTime < 1293840000 THEN '2010-Q4'
       WHEN dateTime < 1301616000 THEN '2011-Q1'
       WHEN dateTime < 1309478400 THEN '2011-Q2'
       WHEN dateTime < 1317427200 THEN '2011-Q3'
       WHEN dateTime < 1325376000 THEN '2011-Q4'
       WHEN dateTime < 1333238400 THEN '2012-Q1'
       WHEN dateTime < 1341100800 THEN '2012-Q2'
       WHEN dateTime < 1349049600 THEN '2012-Q3'
       WHEN dateTime < 1356998400 THEN '2012-Q4'
       WHEN dateTime < 1364774400 THEN '2013-Q1'
       WHEN dateTime < 1372636800 THEN '2013-Q2'
       WHEN dateTime < 1380585600 THEN '2013-Q3'
       WHEN dateTime < 1388534400 THEN '2013-Q4'
       WHEN dateTime < 1396310400 THEN '2014-Q1'
       WHEN dateTime < 1404172800 THEN '2014-Q2'
       WHEN dateTime < 1412121600 THEN '2014-Q3'
       WHEN dateTime < 1420070400 THEN '2014-Q4'
       WHEN dateTime < 1427846400 THEN '2015-Q1'
       WHEN dateTime < 1435708800 THEN '2015-Q2'
       WHEN dateTime < 1443657600 THEN '2015-Q3'
       WHEN dateTime < 1451606400 THEN '2015-Q4'
       WHEN dateTime < 1459468800 THEN '2016-Q1'
       WHEN dateTime < 1467331200 THEN '2016-Q2'
       WHEN dateTime < 1475280000 THEN '2016-Q3'
       WHEN dateTime < 1483228800 THEN '2016-Q4'
       WHEN dateTime < 1491004800 THEN '2017-Q1'
       WHEN dateTime < 1498867200 THEN '2017-Q2'
       WHEN dateTime < 1506816000 THEN '2017-Q3'
       WHEN dateTime < 1514764800 THEN '2017-Q4'
       WHEN dateTime < 1522540800 THEN '2018-Q1'
       WHEN dateTime < 1530403200 THEN '2018-Q2'
       WHEN dateTime < 1538352000 THEN '2018-Q3'
       WHEN dateTime < 1546300800 THEN '2018-Q4'
       WHEN dateTime < 1554076800 THEN '2019-Q1'
       WHEN dateTime < 1561939200 THEN '2019-Q2'
       WHEN dateTime < 1569888000 THEN '2019-Q3'
       WHEN dateTime < 1577836800 THEN '2019-Q4'
       WHEN dateTime < 1585699200 THEN '2020-Q1'
       WHEN dateTime < 1593561600 THEN '2020-Q2'
       WHEN dateTime < 1601510400 THEN '2020-Q3'
       WHEN dateTime < 1609459200 THEN '2020-Q4'
       ELSE 'OUT_OF_RANGE' END AS utc_year_quarter,interval_min,usUnits,COUNT(DISTINCT dateTime) AS timestamps
FROM source_only GROUP BY utc_year_quarter,interval_min,usUnits ORDER BY utc_year_quarter,interval_min,usUnits
